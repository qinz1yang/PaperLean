#!/usr/bin/env python3
"""Generates src/Lean/PaperLean/SpecExclusions.lean: the specialization cache entries of Lean's own
modules as PaperLean builds them that official Lean's modules do not have (outside PaperLean's own
modules, whose entries `PaperLean.ownSpecPath` already keeps from importers).

usage: paperlean-spec-exclusions.py OFFICIAL.tsv PAPERLEAN.tsv OUT.lean
where the TSV files are written by `lean --run script/paperlean-dump-specs.lean OUT.tsv <toolchain>/lib/lean`
with official rc3 and with the PaperLean toolchain (the exclusions act on import, so the dump of a build
with them lists the same entries).
"""
import sys
off_tsv, pl_tsv, out = sys.argv[1:]
rows = lambda f: [l.rstrip('\n').split('\t') for l in open(f) if l.count('\t') >= 2]
off = {r[1] for r in rows(off_tsv)}
excl = sorted({(r[1], int(r[2])) for r in rows(pl_tsv) if r[1] not in off and 'PaperLean' not in r[1]})
hashes = sorted({h for _, h in excl})
names = "\n".join(f"  {n}" for n, _ in excl)
# all hashes in one natural number, 64 bits each, the smallest in the lowest bits (Lean's `prelude`
# arithmetic decodes it; a large array literal is slow to elaborate, and string splitting is not in the
# importer's closure)
packed = sum(h << (64 * i) for i, h in enumerate(hashes))
open(out, 'w').write(f'''/-
Copyright (c) 2026 PaperLean contributors.
Released under Apache 2.0 license as described in the file LICENSE.
-/
module

-- (`prelude` with an import that `Lean.Compiler.LCNF.Specialize` already has: importing all of `Init`
-- would add modules to its importers' environments)
prelude
public import Lean.Environment

set_option genSizeOf false
set_option genInjectivity false

public section

/-!
Generated by `script/paperlean-spec-exclusions.py`; do not edit.

Specializations that Lean's own modules as PaperLean builds them record in their specialization cache
(`Lean.Compiler.LCNF.Specialize`) although official Lean 4.35.0-rc3's modules do not define them: they
are specializations made in the upstream modules whose source PaperLean changes. Code that PaperLean
compiles in another module would call them by name if it reused them, and official Lean, reading
PaperLean's artifacts, could neither link nor interpret that code. Importers therefore do not take these
cache entries and specialize locally instead. They are known by `Name.hash`; another name with one of
these hashes would only be specialized locally too.

The {len(excl)} specializations:
{names}
-/

namespace Lean.PaperLean.SpecExclusions

/-- The hashes (`Name.hash`) of the specializations, sorted, 64 bits each, the first in the lowest
bits (one number rather than a large literal). -/
def packed : Nat := {packed:#x}

/-- The number of hashes in `packed`. -/
def count : Nat := {len(hashes)}

/-- The hashes, sorted. -/
def hashes : Array UInt64 := go count packed (Array.mkEmpty count)
where
  go : Nat → Nat → Array UInt64 → Array UInt64
    | 0, _, acc => acc
    | k + 1, n, acc => go k (n / 18446744073709551616) (acc.push (UInt64.ofNat (n % 18446744073709551616)))

/-- Whether the specialization `n` is one of these (binary search; 64 halvings suffice). -/
def excluded (n : Name) : Bool := go n.hash 64 0 hashes.size
where
  go (h : UInt64) : Nat → Nat → Nat → Bool
    | 0, _, _ => false
    | fuel + 1, lo, hi =>
      if lo < hi then
        let mid := (lo + hi) / 2
        let v := hashes[mid]!
        if v == h then true else if v < h then go h fuel (mid + 1) hi else go h fuel lo mid
      else false

end Lean.PaperLean.SpecExclusions
''')
print(len(excl), 'names', len(hashes), 'hashes')
